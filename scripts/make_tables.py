"""Deterministically turn logged run metrics into a results table.

Reads runs/<run>/metrics.json, aggregates mean +/- std across folds/seeds per
(method, dataset, metric), and writes a CSV and a LaTeX table. No number in the
paper should be typed by hand; regenerate this instead.

Expected metrics.json schema (one per run directory):
    {
      "method": "FACR",
      "dataset": "Aff-Wild2",
      "metrics": {"macro_f1": [0.71, 0.69, 0.72], "acc": [0.80, 0.79, 0.81]}
    }
Each metric maps to a list of per-fold (or per-seed) values.

    python scripts/make_tables.py --runs runs --out paper/tables
"""
from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path


def _mean_std(xs):
    n = len(xs)
    mean = sum(xs) / n
    var = sum((x - mean) ** 2 for x in xs) / (n - 1) if n > 1 else 0.0
    return mean, math.sqrt(var)


def collect(runs_dir: Path):
    rows = []
    for mf in sorted(runs_dir.glob("*/metrics.json")):
        d = json.loads(mf.read_text())
        method = d.get("method", mf.parent.name)
        dataset = d.get("dataset", "?")
        for metric, vals in d.get("metrics", {}).items():
            if not isinstance(vals, list) or not vals:
                continue
            mean, std = _mean_std([float(v) for v in vals])
            rows.append({
                "method": method, "dataset": dataset, "metric": metric,
                "n": len(vals), "mean": mean, "std": std, "run": mf.parent.name,
            })
    return rows


def write_csv(rows, out: Path):
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="") as f:
        w = csv.DictWriter(
            f, fieldnames=["method", "dataset", "metric", "n", "mean", "std", "run"]
        )
        w.writeheader()
        w.writerows(rows)


def write_latex(rows, out: Path):
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "% Auto-generated by scripts/make_tables.py -- do not edit by hand.",
        "\\begin{tabular}{lllr}",
        "\\toprule",
        "Method & Dataset & Metric & Result (mean $\\pm$ std) \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['method']} & {r['dataset']} & {r['metric']} & "
            f"${r['mean']:.3f} \\pm {r['std']:.3f}$ \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default="paper/tables")
    args = ap.parse_args()
    rows = collect(Path(args.runs))
    if not rows:
        print(f"No metrics.json found under {args.runs}/. Nothing written.")
        return
    # Provenance check: every reported number should trace to specific weights.
    missing = [
        mf.parent.name
        for mf in sorted(Path(args.runs).glob("*/metrics.json"))
        if "checkpoint" not in json.loads(mf.read_text())
    ]
    if missing:
        print(f"WARNING: {len(missing)} run(s) have no checkpoint provenance: {missing}")
        print("  -> these numbers cannot be traced to specific weights; record it "
              "via results.log_metrics(..., checkpoint=...).")
    out = Path(args.out)
    write_csv(rows, out / "results.csv")
    write_latex(rows, out / "results.tex")
    print(f"Wrote {len(rows)} row(s) -> {out}/results.csv and results.tex")


if __name__ == "__main__":
    main()

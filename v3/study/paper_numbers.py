"""LaTeX number macros for the world-builder paragraph of the v2 paper (\\wres{key}), from the saved v3 result files.

    python paper_numbers.py            # reads ../results/ablng_all.json, writes ../results/numbers_v3.tex

Source: ablate.py --combine output at the realistic setting (gamma_real, 6 worlds, 4 cost models; the CPC cost model C2
is out of the main tables, STUDY_PROTOCOL deviation 2). Shares are delivered value over the Lagrangian hindsight bound,
as a ratio of totals over complete campaign-days (deviation 3). O-P1 reacts to spend only; O-P4a replays the previous
7 days' opportunities; O-P4g scales that replay to the true expected traffic (deviation 4)."""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results")
D = json.load(open(os.path.join(RES, "ablng_all.json")))
COSTS = ["C1", "C4", "C5", "C6"]
V = {}


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def pts(x, d=1):
    return f"{100 * x:.{d}f}".replace("-", "$-$")


def ci(c, d=1):
    return f"[{pts(c[0], d)}, {pts(c[1], d)}]"


for c in COSTS:
    s = D[c]["share_of_ub"]
    V[f"react-{c}"], V[f"replay-{c}"], V[f"scaled-{c}"] = pct(s["O-P1"]), pct(s["O-P4a"]), pct(s["O-P4g"])
    g = D[c]["gain_over_O-P1"]["O-P4g"]
    V[f"ahead-{c}"], V[f"ahead-ci-{c}"] = pts(g["gain"]), ci(g["ci95"])
    h = D[c]["gain_over_O-P1"]["O-P4a"]
    V[f"replay-gain-{c}"], V[f"replay-gain-ci-{c}"] = pts(h["gain"]), ci(h["ci95"])
    t = D[c]["gain_over_O-P4a"]["O-P4g"]
    V[f"total-{c}"], V[f"total-ci-{c}"] = pts(t["gain"], 2), ci(t["ci95"], 2)
ahead = [D[c]["gain_over_O-P1"]["O-P4g"]["gain"] for c in COSTS]
replay = [D[c]["gain_over_O-P1"]["O-P4a"]["gain"] for c in COSTS]
total = [D[c]["gain_over_O-P4a"]["O-P4g"]["gain"] for c in COSTS]
V["ahead-min"], V["ahead-max"] = pts(min(ahead)), pts(max(ahead))
V["replay-gain-min"], V["replay-gain-max"] = pts(min(replay)), pts(max(replay))
V["total-min"], V["total-max"] = pts(min(total), 1), pts(max(total), 1)
V["ahead-clear"] = str(sum(D[c]["gain_over_O-P1"]["O-P4g"]["ci95"][0] > 0 for c in COSTS))
V["worlds"] = str(D["C1"]["worlds"])
V["costs"] = str(len(COSTS))

lines = ["% Generated by v3/study/paper_numbers.py from v3/results/ablng_all.json. Do not edit by hand.",
         r"\makeatletter", r"\newcommand{\wres}[1]{\@ifundefined{wres@#1}{\textbf{??#1??}}{\csname wres@#1\endcsname}}"]
for k in sorted(V):
    lines.append(rf"\expandafter\def\csname wres@{k}\endcsname{{{V[k]}}}")
lines.append(r"\makeatother")
with open(os.path.join(RES, "numbers_v3.tex"), "w") as f:
    f.write("\n".join(lines) + "\n")
print(len(V), "macros")
for k in ("ahead-min", "ahead-max", "replay-gain-min", "replay-gain-max", "total-min", "total-max", "ahead-clear", "worlds"):
    print(k, V[k])
